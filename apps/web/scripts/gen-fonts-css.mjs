#!/usr/bin/env node
/**
 * Prints @font-face CSS for every font in migration/assets/manifest.json.
 * Usage: `npm run gen:fonts > src/styles/fonts.css`.
 */
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const manifestPath = path.resolve(__dirname, '..', '..', '..', 'migration', 'assets', 'manifest.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

const faceFromFile = (fam, file, weight) => {
  const rel = '/' + file;
  const fmt = file.endsWith('.otf') ? 'opentype' : 'truetype';
  return `@font-face { font-family: '${fam}'; src: url('${rel}') format('${fmt}'); font-weight: ${weight}; font-display: swap; }`;
};

const lines = ['/* auto-generated by scripts/gen-fonts-css.mjs */', ''];
for (const entry of manifest.fonts.latin) {
  lines.push(faceFromFile(entry.family, entry.file, entry.weight));
}
for (const entry of manifest.fonts.arabic_body_primary) {
  lines.push(faceFromFile(entry.family, entry.file, entry.weight));
}
const secondary = manifest.fonts.arabic_body_secondary;
lines.push(faceFromFile(secondary.family, secondary.file, secondary.weight));
const display = manifest.fonts.arabic_display;
lines.push(faceFromFile(display.family, display.file, display.weight));
for (const entry of manifest.fonts.arabic_system_fallback) {
  lines.push(faceFromFile(entry.family, entry.file, entry.weight));
}
lines.push('');
lines.push('/* Font variables are owned by brand-tokens.css per Brand Guidelines 2026 p.22-23 */');
lines.push('/* (Readex Pro is the PRIMARY typeface for BOTH Arabic and Latin)                    */');
process.stdout.write(lines.join('\n') + '\n');
